/**
 * Случайное число от 0 до max
 */
export function R(max) {
    return Math.random() * max;
}

/**
 * Случайное число в диапазоне [-range/2, +range/2]
 */
export function RD(range) {
    return -range / 2 + Math.random() * range;
}
